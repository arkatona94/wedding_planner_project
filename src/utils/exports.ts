export function generateShareableLink(
  data: {
    guests?: Guest[]
    timeline?: TimelineEvent[]
    weddingDetails?: {
      coupleNames: string
      weddingDate: string
      venue: string
    }
  },
  type: 'rsvp' | 'timeline' | 'info'
): string {
  // Encode essential data for shareable link
  const shareData = {
    type,
    ...data,
    generated: new Date().toISOString()
  }

  // Create a base64 encoded string (in production, you'd use a backend with proper URLs)
  const encoded = btoa(JSON.stringify(shareData))

  // For now, return a hash-based URL that works client-side
  return `${window.location.origin}/share#${encoded}`
}

export function parseShareableLink(hash: string): any {
  try {
    const encoded = hash.replace('#', '')
    return JSON.parse(atob(encoded))
  } catch {
    return null
  }
}
