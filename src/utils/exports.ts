// ICS CALENDAR EXPORT
// ============================================

export function exportTimelineICS(
  events: TimelineEvent[],
  weddingDate: string,
  coupleNames: string
): void {
  if (!weddingDate) {
    alert('Please set your wedding date first')
    return
  }

  const formatICSDate = (date: string, time: string): string => {
    const [year, month, day] = date.split('-')
    const [hours, minutes] = time.split(':')
    return `${year}${month}${day}T${hours}${minutes}00`
  }

  const escapeICS = (text: string): string => {
    return text
      .replace(/\\/g, '\\\\')
      .replace(/;/g, '\\;')
      .replace(/,/g, '\\,')
      .replace(/\n/g, '\\n')
  }

  const icsEvents = events.map((event) => {
    const uid = `${event.id}@beginnings-and-endings-wedding`
    const dtStart = formatICSDate(weddingDate, event.startTime)
    const dtEnd = formatICSDate(weddingDate, event.endTime)
    const summary = escapeICS(event.title)
    const location = event.location ? escapeICS(event.location) : ''
    const description = event.description ? escapeICS(event.description) : ''

    return [
      'BEGIN:VEVENT',
      `UID:${uid}`,
      `DTSTAMP:${formatICSDate(new Date().toISOString().split('T')[0], '00:00')}`,
      `DTSTART:${dtStart}`,
      `DTEND:${dtEnd}`,
      `SUMMARY:${summary}`,
      location ? `LOCATION:${location}` : '',
      description ? `DESCRIPTION:${description}` : '',
      'END:VEVENT'
    ].filter(Boolean).join('\r\n')
  }).join('\r\n')

  const icsContent = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//Beginnings and Endings Wedding Planner//EN',
    `X-WR-CALNAME:${escapeICS(coupleNames)} Wedding`,
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    icsEvents,
    'END:VCALENDAR'
  ].join('\r\n')

  // Download the file
  const blob = new Blob([icsContent], { type: 'text/calendar;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = `wedding-timeline-${weddingDate}.ics`
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
  URL.revokeObjectURL(url)
}

